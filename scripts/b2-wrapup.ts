// B2 wrap-up audit: cross-level checks on all B2 lessons, written to docs/b2-wrapup.md.
// Run with: node --experimental-strip-types scripts/b2-wrapup.ts
// It never fails; read the report.
import fs from "node:fs";
import path from "node:path";
import matter from "gray-matter";
import { splitSections, teachingText, italicLines, resumeWords } from "./lesson-text.ts";
import { NEW_MEANINGS } from "./b2-lists.ts";

const ROOT = process.cwd();
const LEVELS = ["a1", "a2", "b1", "b2"];
type Lesson = { id: string; level: string; rank: number; order: number; unit: string; type: string; title: string; body: string; raw: string; vocab: any[]; exercises: any[]; prerequisites: string[] };

const lessons: Lesson[] = [];
for (const [rank, lv] of LEVELS.entries()) {
  const dir = path.join(ROOT, "content", "lessons", lv);
  if (!fs.existsSync(dir)) continue;
  for (const f of fs.readdirSync(dir).filter((x) => x.endsWith(".mdx"))) {
    const raw = fs.readFileSync(path.join(dir, f), "utf8").replace(/\r\n/g, "\n");
    const { data, content } = matter(raw);
    lessons.push({ id: data.id, level: lv, rank, order: data.order, unit: data.unit, type: data.type, title: data.title, body: content, raw: raw.toLowerCase(), vocab: data.vocab ?? [], exercises: data.exercises ?? [], prerequisites: data.prerequisites ?? [] });
  }
}
lessons.sort((a, b) => a.rank - b.rank || a.order - b.order);
const byId = new Map(lessons.map((l) => [l.id, l]));
const b2 = lessons.filter((l) => l.level === "b2");
const earlier = lessons.filter((l) => l.rank < 3);

// Unit numbers and planned ids from the syllabus.
const unitNumber = new Map<string, number>();
const planned = new Set<string>();
let cur = 0;
for (const line of fs.readFileSync(path.join(ROOT, "docs", "syllabus.md"), "utf8").split(/\r?\n/)) {
  const u = line.match(/^### Unit (\d+)/);
  if (u) cur = Number(u[1]);
  const m = line.match(/^\|\s*\d+\s*\|\s*([abc][12]-[^\s|]+)\s*\|/);
  if (m) { planned.add(m[1]); unitNumber.set(m[1], cur); }
}

// Same word count as audit-content.ts.
const attr = (tag: string, name: string) => tag.match(new RegExp(name + '="([^"]*)"'))?.[1] ?? null;
const countWords = (t: string) => t.split(/\s+/).filter((w) => /[\p{L}\p{N}]/u.test(w)).length;
const renderedWords = (text: string) => {
  let b = text.replace(/<VocabTable[^>]*\/>/g, " ");
  b = b.replace(/<Example\b[^>]*\/>/g, (t) => ` ${attr(t, "fr") ?? ""} ${attr(t, "en") ?? ""} `);
  b = b.replace(/<LessonLink\b[^>]*\/>/g, (t) => ` ${attr(t, "text") ?? byId.get(attr(t, "id") ?? "")?.title ?? ""} `);
  b = b.replace(/<Callout\b[^>]*>/g, (t) => ` ${attr(t, "title") ?? ""} `).replace(/<[^>]+>/g, " ");
  b = b.replace(/^\|[\s:|-]+\|\s*$/gm, " ").replace(/[*|#]/g, " ");
  return countWords(b);
};
const norm = (s: string) => s.normalize("NFC").toLowerCase().replace(/[’]/g, "'").replace(/[«»"]/g, "").replace(/\s+/g, " ").replace(/[\s.!?…]+$/, "").trim();
const sentencesOf = (l: Lesson) => [
  ...[...l.body.matchAll(/<Example fr="([^"]*)"/g)].map((m) => m[1]),
  ...splitSections(l.body).filter((s) => s.kind === "dialogue" || s.kind === "text").flatMap((s) => italicLines(s.body)),
].map(norm).filter((s) => s.split(" ").length >= 3);
const tipsOf = (l: Lesson) => [...l.body.matchAll(/<Callout type="tip"[^>]*>([\s\S]*?)<\/Callout>/g)].map((m) => norm(m[1]));

const out: string[] = ["# B2 wrap-up audit", "", `Generated by \`node --experimental-strip-types scripts/b2-wrapup.ts\`. ${b2.length} B2 lessons checked against ${earlier.length} A1 to B1 lessons.`, ""];
// Judgement calls from the wrap-up, kept here so a rerun doesn't lose them.
out.push("## Judgement calls for the editor", "",
  "- **Forward signposts.** Nine lessons point to a later B2 lesson outside What's next (listed below). They label a form or a phrase as taught later (for example *se faire voler* before b2-faire-causatif), which the fixed-phrase rule asks for. Keep them, or turn each into plain text without a LessonLink?",
  "- **un tableau** is an entry in b2-presenting-data (a table) and b2-arts-and-literature (a painting). The second note marks the new meaning; NEW_MEANINGS only covers A1 to B1, so no list change is needed. Accept?",
  "- **c1-passe-simple** is linked from b2-review-final but has no file yet; it's planned in the syllabus and shows as Coming soon. Accept until C1 is written?",
  "- **Repeated phrase.** *à côté de* appears in b2-relative-lequel and b2-review-pronouns: a three-word phrase, not a copied sentence. Accept?",
  "- **Claim flags.** The claims list below includes artefacts (inflected forms, or a term that belongs to another link in the same sentence). The real ones were fixed; the rest were checked by hand.",
  "");
const section = (title: string, rows: string[]) => { out.push(`## ${title}`, ""); out.push(...(rows.length ? rows.map((r) => `- ${r}`) : ["None."])); out.push(""); };

// 1. Links.
const linkRows: string[] = [];
const forwardRows: string[] = [];
for (const l of b2) {
  for (const p of l.prerequisites) if (!byId.has(p)) linkRows.push(`${l.id}: prerequisite ${p} has no lesson file`);
  const sections = splitSections(l.body);
  for (const s of sections) {
    for (const m of s.body.matchAll(/<LessonLink\b[^>]*id="([^"]+)"/g)) {
      const t = byId.get(m[1]);
      if (!t) { linkRows.push(`${l.id}: LessonLink to ${m[1]} has no lesson file${planned.has(m[1]) ? " (planned in the syllabus)" : ""}`); continue; }
      if (t.rank === l.rank && t.order > l.order && s.heading !== "What's next") forwardRows.push(`${l.id} (section "${s.heading}"): links forward to ${t.id} (order ${t.order})`);
    }
  }
}
section("Missing link targets", linkRows);
section("Forward links outside What's next", forwardRows);

// 2. Repeats.
const vocabRows: string[] = [];
const seenEarlierVocab = new Map<string, string>();
for (const l of earlier) for (const v of l.vocab) { const k = norm(String(v.fr)); if (!seenEarlierVocab.has(k)) seenEarlierVocab.set(k, l.id); }
const seenB2Vocab = new Map<string, string>();
for (const l of b2) for (const v of l.vocab) {
  const k = norm(String(v.fr));
  if (seenEarlierVocab.has(k) && !(k in NEW_MEANINGS)) vocabRows.push(`${l.id} (${v.id}): "${v.fr}" repeats ${seenEarlierVocab.get(k)}`);
  if (seenB2Vocab.has(k)) vocabRows.push(`${l.id} (${v.id}): "${v.fr}" is also an entry in ${seenB2Vocab.get(k)} (B2)`);
  else seenB2Vocab.set(k, l.id);
}
section("Vocab entries repeated (B2 vs A1 to B1 outside NEW_MEANINGS, and across B2)", vocabRows);

const sentRows: string[] = [];
const earlierSent = new Map<string, string>();
for (const l of earlier) for (const s of sentencesOf(l)) if (!earlierSent.has(s)) earlierSent.set(s, l.id);
const earlierTips = new Map<string, string>();
for (const l of earlier) for (const s of tipsOf(l)) earlierTips.set(s, l.id);
const b2Sent = new Map<string, string>();
const b2Tips = new Map<string, string>();
for (const l of b2) {
  for (const s of new Set(sentencesOf(l))) {
    if (earlierSent.has(s)) sentRows.push(`${l.id}: "${s}" is also in ${earlierSent.get(s)}`);
    if (b2Sent.has(s)) sentRows.push(`${l.id}: "${s}" is also in ${b2Sent.get(s)} (B2)`);
    else b2Sent.set(s, l.id);
  }
  for (const s of tipsOf(l)) {
    if (earlierTips.has(s)) sentRows.push(`${l.id}: tip copied from ${earlierTips.get(s)}`);
    if (b2Tips.has(s)) sentRows.push(`${l.id}: tip copied from ${b2Tips.get(s)} (B2)`);
    else b2Tips.set(s, l.id);
  }
}
section("French sentences or tips repeated", sentRows);

// 3. "You know X from lesson Y" claims.
const claimRows: string[] = [];
const claimFlags: string[] = [];
for (const l of b2) {
  for (const para of l.body.split(/\n\n/)) {
    if (!/\b(?:you know|you've met|you met|you've seen|you learned|you've used|you've already)\b/i.test(para)) continue;
    let prev = 0;
    for (const m of para.matchAll(/<LessonLink\b[^>]*id="([^"]+)"[^>]*\/>/g)) {
      const seg = para.slice(prev, m.index);
      prev = (m.index ?? 0) + m[0].length;
      const sentence = seg.split(/(?<=[.!?:;])\s+/).pop() ?? seg;
      if (!/\b(?:know|met|seen|learned|used|already)\b/i.test(sentence)) continue;
      // Bold labels (**Unit 1.**) aren't claimed words; only single-asterisk italics are.
      const terms = [...sentence.replace(/\*\*[^*]+\*\*/g, " ").matchAll(/\*([^*]+)\*/g)].map((x) => x[1].replace(/[…]/g, "").trim()).filter((x) => x.length > 1);
      const target = byId.get(m[1]);
      for (const term of terms) {
        const ok = !!target && target.raw.includes(term.toLowerCase());
        claimRows.push(`${l.id}: *${term}* from ${m[1]}${ok ? "" : " — NOT FOUND in that lesson"}`);
        if (!ok) claimFlags.push(`${l.id}: *${term}* claimed from ${m[1]}, not found in its text or vocab`);
      }
    }
  }
}
section("Claims not found in the linked lesson (check by hand: some are inflected forms)", claimFlags);

// 4. Per-unit statistics, and 5. limits.
const limitRows: string[] = [];
const units = new Map<string, Lesson[]>();
for (const l of b2) { if (!units.has(l.unit)) units.set(l.unit, []); units.get(l.unit)!.push(l); }
out.push("## Per unit", "", "| Unit | Lessons | Teaching words | En résumé words | Exercises by type | Dialogue lines |", "|---|---|---|---|---|---|");
for (const [unit, ls] of units) {
  const teach = ls.map((l) => renderedWords(teachingText(l.body)));
  const res = ls.map((l) => resumeWords(l.body)).filter((n) => n > 0);
  const types = new Map<string, number>();
  for (const l of ls) for (const e of l.exercises) types.set(e.type, (types.get(e.type) ?? 0) + 1);
  const dlines = ls.map((l) => {
    const d = splitSections(l.body).find((s) => s.kind === "dialogue");
    return d ? d.body.split("\n").filter((x) => /^- /.test(x.trim())).length : 0;
  }).filter((n) => n > 0);
  const range = (a: number[]) => (a.length ? `${Math.min(...a)} to ${Math.max(...a)}` : "—");
  out.push(`| ${unitNumber.get(ls[0].id) ?? "?"}. ${unit} | ${ls.length} | ${range(teach)} | ${range(res)} | ${[...types].map(([t, n]) => `${t} ${n}`).join(", ")} | ${range(dlines)} |`);
  for (const l of ls) {
    const t = renderedWords(teachingText(l.body));
    const whole = renderedWords(l.body);
    const maxT = l.type === "grammar" ? 1200 : 1100;
    if (t < 800 || t > maxT) limitRows.push(`${l.id}: teaching text ${t} (800 to ${maxT})`);
    if (whole > 1800) limitRows.push(`${l.id}: whole lesson ${whole} (max 1,800)`);
    const voc = l.vocab.filter((v) => v.group !== "glossary").length;
    const [lo, hi] = l.type === "review" ? [3, 8] : l.type === "grammar" ? [12, 30] : [15, 30];
    if (voc < lo || voc > hi) limitRows.push(`${l.id}: ${voc} vocab entries (${lo} to ${hi})`);
    if (l.exercises.length < 14 || l.exercises.length > 16) limitRows.push(`${l.id}: ${l.exercises.length} exercises (14 to 16)`);
    const d = splitSections(l.body).find((s) => s.kind === "dialogue");
    if (d) { const n = d.body.split("\n").filter((x) => /^- /.test(x.trim())).length; if (n < 10 || n > 14) limitRows.push(`${l.id}: dialogue ${n} lines (10 to 14)`); }
    const r = resumeWords(l.body);
    const un = unitNumber.get(l.id) ?? 0;
    const [rlo, rhi] = un >= 5 ? [100, 150] : [60, 100];
    if (r && (r < rlo || r > rhi)) limitRows.push(`${l.id}: En résumé ${r} (${rlo} to ${rhi})`);
    if (l.type === "communication" || l.type === "culture") {
      const w = countWords(splitSections(l.body).filter((s) => s.kind === "text").flatMap((s) => italicLines(s.body)).join(" "));
      if (w < 150 || w > 250) limitRows.push(`${l.id}: longer text ${w} French words (150 to 250)`);
    }
  }
}
out.push("");
section("Over a CLAUDE.md limit", limitRows);
section("All claims checked (for reference)", claimRows);

fs.writeFileSync(path.join(ROOT, "docs", "b2-wrapup.md"), out.join("\n"));
console.log(`b2-wrapup: ${linkRows.length} missing targets, ${forwardRows.length} forward links, ${vocabRows.length} vocab repeats, ${sentRows.length} sentence/tip repeats, ${claimFlags.length} claim flags, ${limitRows.length} limit rows`);
