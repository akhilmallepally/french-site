// C1 coverage map: what A1 to B2 already teach, by lesson id, so C1 lessons can recap and link
// instead of re-teaching. Writes docs/c1-coverage.md.
// Run with: node --experimental-strip-types scripts/c1-lists.ts
import fs from "node:fs";
import path from "node:path";
import matter from "gray-matter";

const ROOT = process.cwd();
const LEVELS = ["a1", "a2", "b1", "b2"];
type Lesson = { id: string; level: string; order: number; type: string; title: string; vocab: { fr: string }[] };

const lessons: Lesson[] = [];
for (const lv of LEVELS) {
  const dir = path.join(ROOT, "content", "lessons", lv);
  for (const f of fs.readdirSync(dir).filter((x) => x.endsWith(".mdx"))) {
    const { data } = matter(fs.readFileSync(path.join(dir, f), "utf8"));
    lessons.push({ id: data.id, level: lv, order: data.order, type: data.type, title: data.title, vocab: data.vocab ?? [] });
  }
}
lessons.sort((a, b) => LEVELS.indexOf(a.level) - LEVELS.indexOf(b.level) || a.order - b.order);

// Tenses and moods: grammar lessons whose title names one.
export const TENSE_WORDS = /present|présent|passé|imparfait|futur|future|conditionnel|conditional|subjonctif|subjunctive|plus-que-parfait|infinitif|infinitive|participle|participe|gérondif|imperative|passive/i;
// Connectors and discourse markers, matched against vocab entries.
export const CONNECTORS = /^(?:pourtant|cependant|néanmoins|toutefois|en revanche|alors que|tandis que|bien que|quoique|même si|malgré|certes|par conséquent|donc|ainsi|en effet|en outre|de plus|d'ailleurs|d'une part|d'autre part|en résumé|en somme|bref|finalement|enfin|d'abord|ensuite|puis|parce que|puisque|car|comme|grâce à|à cause de|si bien que|de sorte que|afin que|afin de|pour que|de peur que|à condition que|à moins que|avant que|jusqu'à ce que|sans que|étant donné|du coup|en gros|or|quant à|pour ce qui est de|qui plus est|sans compter que|d'où|dès que|lorsque|une fois que|au cas où|sinon)\b/i;
// Fixed phrases: multi-word vocab entries built on a common verb, plus every entry of an idioms lesson.
const FIXED = /^(?:avoir|être|faire|mettre|prendre|tenir|donner|tirer|passer|poser|tomber|couper|en |il y a|ça )\S*\s+\S+\s+\S+/i;

const grammar = lessons.filter((l) => l.type === "grammar");
const tenses = grammar.filter((l) => TENSE_WORDS.test(l.title));
const connectors = new Map<string, string>();
const fixed = new Map<string, string>();
for (const l of lessons) {
  for (const v of l.vocab) {
    const fr = String(v.fr).split(/\s*\/\s*/)[0].trim();
    if (CONNECTORS.test(fr) && !connectors.has(fr.toLowerCase())) connectors.set(fr.toLowerCase(), `${fr} (${l.id})`);
    if ((FIXED.test(fr) || /idioms/.test(l.id)) && !fixed.has(fr.toLowerCase())) fixed.set(fr.toLowerCase(), `${fr} (${l.id})`);
  }
}

const out: string[] = [
  "# C1 coverage map",
  "",
  `Generated by \`node --experimental-strip-types scripts/c1-lists.ts\` from ${lessons.length} A1 to B2 lessons. Before a C1 lesson teaches something, look it up here: if it's listed, recap it in 2 or 3 sentences and link the lesson.`,
  "",
  "## Tenses and moods (grammar lessons)",
  "",
  ...tenses.map((l) => `- ${l.title}: \`${l.id}\``),
  "",
  "## All grammar lessons, by level",
  "",
];
for (const lv of LEVELS) {
  const ls = grammar.filter((l) => l.level === lv);
  out.push(`**${lv.toUpperCase()}** (${ls.length}): ${ls.map((l) => `${l.title} \`${l.id}\``).join("; ")}`, "");
}
out.push("## Connectors and discourse markers", "", [...connectors.values()].join("; "), "");
out.push(`## Fixed phrases and idioms (${fixed.size})`, "", [...fixed.values()].join("; "), "");
fs.writeFileSync(path.join(ROOT, "docs", "c1-coverage.md"), out.join("\n"));
console.log(`c1-lists: ${tenses.length} tense lessons, ${grammar.length} grammar lessons, ${connectors.size} connectors, ${fixed.size} fixed phrases`);
